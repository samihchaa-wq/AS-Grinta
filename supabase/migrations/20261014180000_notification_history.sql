begin;

-- Historique des notifications de chaque joueur.
--
-- Jusqu'ici, une notification n'existait que sur le téléphone : si elle avait
-- été bloquée, effacée, ou si le joueur n'avait aucun appareil abonné, rien ne
-- permettait de la relire. Le texte envoyé n'était d'ailleurs gardé nulle
-- part côté serveur.
--
-- Chaque envoi du club est désormais rangé ici, pour chacun de ses
-- destinataires, même quand aucun téléphone ne l'a affiché. La cloche de
-- l'application lit cet historique et compte les notifications non lues ; ce
-- même nombre remplace la pastille de l'icône de l'application.
--
-- Règles :
--
-- - l'enregistrement est fait par la fonction d'envoi (service interne
--   uniquement), après le coupe-circuit : rien n'est rangé pendant une pause
--   des notifications, et les envois de test ne passent jamais par ici ;
-- - 90 jours de conservation : au-delà, une ligne n'est plus jamais rendue et
--   elle est supprimée au fil des enregistrements suivants ;
-- - une notification devient lue quand le joueur ouvre l'écran, ou quand il
--   fait ce qu'elle lui demandait (répondre à la disponibilité, remplir son
--   pronostic, voter pour l'homme du match) ;
-- - le joueur peut supprimer une ligne ; la suppression du compte efface tout
--   son historique par cascade.

create table if not exists private.notification_history (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  kind text not null
    check (kind ~ '^[a-z][a-z0-9_]*$' and char_length(kind) <= 64),
  match_id uuid references public.matches(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 200),
  body text not null default '' check (char_length(body) <= 1000),
  url text check (url is null or char_length(url) <= 512),
  tag text check (tag is null or char_length(tag) <= 200),
  dedupe_key text check (dedupe_key is null or char_length(dedupe_key) <= 200),
  created_at timestamptz not null default now(),
  read_at timestamptz
);

comment on table private.notification_history is
  'Notifications envoyées par le club à chaque joueur, même quand aucun téléphone ne les a affichées. Lues par les RPC get_my_*, conservées 90 jours.';

comment on column private.notification_history.dedupe_key is
  'Clé optionnelle qui empêche de ranger deux fois le même envoi pour un joueur (par exemple live:<id> ou sport_event:<id>).';

comment on column private.notification_history.read_at is
  'Moment où le joueur a ouvert l écran des notifications ou fait ce que la notification demandait. NULL : non lue.';

create index if not exists notification_history_profile_created_idx
  on private.notification_history (profile_id, created_at desc, id desc);

create unique index if not exists notification_history_profile_dedupe_idx
  on private.notification_history (profile_id, dedupe_key)
  where dedupe_key is not null;

create index if not exists notification_history_unread_idx
  on private.notification_history (profile_id)
  where read_at is null;

create index if not exists notification_history_match_idx
  on private.notification_history (match_id);

create index if not exists notification_history_created_at_idx
  on private.notification_history (created_at);

-- Lecture et écriture réservées aux fonctions ci-dessous et au service
-- interne : refus par défaut.
alter table private.notification_history enable row level security;
revoke all on table private.notification_history from public, anon, authenticated;

-- ---------------------------------------------------------------------------
-- Enregistrement (service interne)
-- ---------------------------------------------------------------------------

-- Appelée par la fonction d'envoi au moment où une notification part. Elle
-- range une ligne par destinataire actif et rend, pour chacun, son nombre de
-- notifications non lues : la fonction d'envoi le glisse dans la
-- notification pour mettre à jour la pastille de l'icône.
--
-- Elle ne doit jamais faire échouer un envoi : un match supprimé entre-temps
-- est simplement oublié, les textes trop longs sont coupés, un type inconnu
-- est rangé comme « custom » et une adresse trop longue n'est pas gardée
-- (une adresse coupée mènerait nulle part).
create or replace function public.internal_record_notification_history(
  p_kind text,
  p_match_id uuid,
  p_profile_ids uuid[],
  p_title text,
  p_body text,
  p_url text,
  p_tag text,
  p_dedupe_key text default null
)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_kind text := case
    when p_kind ~ '^[a-z][a-z0-9_]*$' and char_length(p_kind) <= 64 then p_kind
    else 'custom'
  end;
  v_title text := left(btrim(coalesce(p_title, '')), 200);
  v_body text := left(btrim(coalesce(p_body, '')), 1000);
  v_url text := nullif(btrim(coalesce(p_url, '')), '');
  v_tag text := left(nullif(btrim(coalesce(p_tag, '')), ''), 200);
  v_dedupe_key text := left(nullif(btrim(coalesce(p_dedupe_key, '')), ''), 200);
  v_match_id uuid;
  v_profile_ids uuid[];
  v_unread jsonb;
begin
  if char_length(v_url) > 512 then
    v_url := null;
  end if;

  -- Seuls les profils actifs ont un historique ; un identifiant répété
  -- n'est compté qu'une fois.
  select coalesce(array_agg(profile.id order by profile.id), '{}'::uuid[])
  into v_profile_ids
  from public.profiles profile
  where profile.id = any(coalesce(p_profile_ids, '{}'::uuid[]))
    and profile.status = 'active';

  -- Rien n'est rangé pendant la pause des notifications : rien n'est envoyé.
  if v_title <> ''
     and cardinality(v_profile_ids) > 0
     and not private.is_feature_enabled('notifications_paused') then
    if p_match_id is not null then
      -- Le verrou empêche la suppression du match avant la fin de
      -- l'enregistrement ; un match déjà supprimé est simplement oublié.
      select match.id
      into v_match_id
      from public.matches match
      where match.id = p_match_id
      for key share;
    end if;

    insert into private.notification_history (
      profile_id, kind, match_id, title, body, url, tag, dedupe_key
    )
    select
      recipient.profile_id,
      v_kind,
      v_match_id,
      v_title,
      v_body,
      v_url,
      v_tag,
      v_dedupe_key
    from unnest(v_profile_ids) as recipient(profile_id)
    on conflict (profile_id, dedupe_key) where dedupe_key is not null
    do nothing;
  end if;

  delete from private.notification_history history
  where history.created_at < now() - interval '90 days';

  select coalesce(
    jsonb_object_agg(recipient.profile_id::text, unread.total),
    '{}'::jsonb
  )
  into v_unread
  from unnest(v_profile_ids) as recipient(profile_id)
  cross join lateral (
    select count(*)::integer as total
    from private.notification_history history
    where history.profile_id = recipient.profile_id
      and history.read_at is null
      and history.created_at >= now() - interval '90 days'
  ) unread;

  return v_unread;
end;
$function$;

comment on function public.internal_record_notification_history(text, uuid, uuid[], text, text, text, text, text) is
  'Range une notification envoyée dans l historique de chaque destinataire actif et rend leur nombre de notifications non lues. Service interne uniquement.';

revoke all on function public.internal_record_notification_history(text, uuid, uuid[], text, text, text, text, text)
  from public, anon, authenticated;
grant execute on function public.internal_record_notification_history(text, uuid, uuid[], text, text, text, text, text)
  to service_role;

-- ---------------------------------------------------------------------------
-- Lecture et gestion par le joueur
-- ---------------------------------------------------------------------------
--
-- Chaque fonction ne touche que les lignes du compte connecté. Un profil
-- archivé ou en attente lit un historique vide et un compteur à zéro (l'écran
-- reste affichable sans erreur), mais ne peut ni marquer comme lu ni
-- supprimer.

create or replace function public.get_my_notification_history(
  p_limit integer default 100
)
returns table (
  id bigint,
  kind text,
  match_id uuid,
  title text,
  body text,
  url text,
  created_at timestamptz,
  read_at timestamptz
)
language plpgsql
stable
security definer
set search_path to ''
as $function$
declare
  v_actor uuid := (select auth.uid());
  v_limit integer := least(greatest(coalesce(p_limit, 100), 1), 200);
begin
  if v_actor is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if not exists (
    select 1
    from public.profiles profile
    where profile.id = v_actor
      and profile.status = 'active'
  ) then
    return;
  end if;

  return query
  select
    history.id,
    history.kind,
    history.match_id,
    history.title,
    history.body,
    history.url,
    history.created_at,
    history.read_at
  from private.notification_history history
  where history.profile_id = v_actor
    and history.created_at >= now() - interval '90 days'
  order by history.created_at desc, history.id desc
  limit v_limit;
end;
$function$;

comment on function public.get_my_notification_history(integer) is
  'Notifications des 90 derniers jours du compte connecté, la plus récente en premier (200 au plus). Vide pour un profil non actif.';

revoke all on function public.get_my_notification_history(integer)
  from public, anon;
grant execute on function public.get_my_notification_history(integer)
  to authenticated, service_role;

