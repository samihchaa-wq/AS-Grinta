create or replace function public.mark_my_notifications_read()
returns integer
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_actor uuid := (select auth.uid());
  v_count integer;
begin
  if v_actor is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if not exists (
    select 1
    from public.profiles profile
    where profile.id = v_actor
      and profile.status = 'active'
  ) then
    raise exception 'Active profile not found' using errcode = '42501';
  end if;

  update private.notification_history history
  set read_at = now()
  where history.profile_id = v_actor
    and history.read_at is null
    and history.created_at >= now() - interval '90 days';

  get diagnostics v_count = row_count;
  return v_count;
end;
$function$;

comment on function public.mark_my_notifications_read() is
  'Marque comme lues toutes les notifications non lues du compte connecté et rend leur nombre. Profil actif exigé.';

revoke all on function public.mark_my_notifications_read()
  from public, anon;
grant execute on function public.mark_my_notifications_read()
  to authenticated, service_role;

create or replace function public.delete_my_notification(p_id bigint)
returns boolean
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_actor uuid := (select auth.uid());
begin
  if v_actor is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if not exists (
    select 1
    from public.profiles profile
    where profile.id = v_actor
      and profile.status = 'active'
  ) then
    raise exception 'Active profile not found' using errcode = '42501';
  end if;

  -- Seule une ligne du demandeur peut être supprimée ; l'identifiant d'une
  -- ligne d'un autre compte ne supprime rien.
  delete from private.notification_history history
  where history.id = p_id
    and history.profile_id = v_actor;

  return found;
end;
$function$;

comment on function public.delete_my_notification(bigint) is
  'Supprime définitivement une notification de l historique du compte connecté. Rend false si la ligne n existe pas ou appartient à un autre compte. Profil actif exigé.';

revoke all on function public.delete_my_notification(bigint)
  from public, anon;
