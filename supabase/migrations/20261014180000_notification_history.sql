drop trigger if exists trg_mark_notifications_read_on_availability
  on public.match_sport_participant_events;

create trigger trg_mark_notifications_read_on_availability
after insert on public.match_sport_participant_events
for each row
when (
  new.event_type = 'availability_changed'
  and new.actor_kind = 'player'
  and new.actor_profile_id is not null
  and coalesce(new.new_value ->> 'status', 'no_response') <> 'no_response'
)
execute function private.mark_notifications_read_on_availability_answer();

drop trigger if exists trg_mark_notifications_read_on_prediction
  on public.match_predictions;

create trigger trg_mark_notifications_read_on_prediction
after insert or update of is_filled on public.match_predictions
for each row
when (new.is_filled)
execute function private.mark_notifications_read_on_prediction();

drop trigger if exists trg_mark_notifications_read_on_motm_vote
  on public.match_sport_motm_votes;

create trigger trg_mark_notifications_read_on_motm_vote
after insert on public.match_sport_motm_votes
for each row
execute function private.mark_notifications_read_on_motm_vote();

