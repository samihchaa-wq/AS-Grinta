  to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- Lu en faisant ce que la notification demandait
-- ---------------------------------------------------------------------------
--
-- Une notification qui demande une action devient lue dès que le joueur l'a
-- faite, même sans ouvrir l'écran des notifications. Ces déclencheurs
-- s'appuient sur les tables que les actions écrivent déjà, sans toucher aux
-- fonctions des actions. Ils ne doivent jamais faire échouer l'action du
-- joueur : toute erreur est ignorée.

-- Disponibilité : seule une vraie réponse du joueur compte (présent ou
-- absent, y compris l'absence posée par une période d'indisponibilité qu'il
-- déclare). Une modification par le staff ou le retour à « pas de réponse »
-- quand une période est annulée ne marquent rien comme lu.
create or replace function private.mark_notifications_read_on_availability_answer()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
begin
  update private.notification_history history
  set read_at = now()
  where history.profile_id = new.actor_profile_id
    and history.match_id = new.match_id
    and history.kind in (
      'availability_open',
      'availability_manual',
      'match_rescheduled_date'
    )
    and history.read_at is null;

  return new;
exception when others then
  return new;
end;
$function$;

