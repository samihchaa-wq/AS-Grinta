-- Toutes les identités qui restent sans relation certaine sont volontairement
-- séparées. Les libellés strictement identiques et non résolus forment une
-- seule nouvelle identité ; une collision avec plusieurs identités existantes
-- crée au contraire une identité distincte au lieu de choisir arbitrairement.
create temporary table _canonical_player_seed on commit drop as
with alias_count as (
  select
    private.normalize_player_name(a.alias) as normalized_name,
    count(distinct a.player_id) as identity_count
  from public.player_aliases a
  group by private.normalize_player_name(a.alias)
),
archive_names as (
  select distinct
    private.normalize_player_name(n.player_name) as normalized_name,
    btrim(n.player_name) as display_name
  from public.historical_match_details h
  cross join lateral (
    select e ->> 'name' as player_name
    from jsonb_array_elements(coalesce(h.field_players, '[]'::jsonb)) e
    union all
    select jsonb_array_elements_text(coalesce(h.bench_players, '[]'::jsonb))
    union all
    select jsonb_array_elements_text(coalesce(h.present_names, '[]'::jsonb))
    union all
    select e ->> 'name'
    from jsonb_array_elements(coalesce(h.scorers, '[]'::jsonb)) e
    union all
    select jsonb_array_elements_text(coalesce(h.motm_names, '[]'::jsonb))
  ) n
  where btrim(coalesce(n.player_name, '')) <> ''
    and private.normalize_player_name(n.player_name)
      <> private.normalize_player_name('Poste laissé vide')
),
candidate as (
  select
    private.normalize_player_name(
      concat_ws(' ', sp.first_name, nullif(sp.last_name, ''))
    ) as normalized_name,
    btrim(concat_ws(' ', sp.first_name, nullif(sp.last_name, ''))) as display_name,
    10 as priority
  from public.season_players sp
  where sp.player_id is null

  union all

  select
    private.normalize_player_name(
      concat_ws(' ', g.first_name, nullif(g.last_name, ''))
    ),
    btrim(concat_ws(' ', g.first_name, nullif(g.last_name, ''))),
    20
  from public.guest_players g
  where g.player_id is null

  union all

  select
    private.normalize_player_name(h.player_name),
    btrim(h.player_name),
    30
  from public.historical_player_statistics h
  where h.player_id is null

  union all

  select an.normalized_name, an.display_name, 40
  from archive_names an
  left join alias_count ac using (normalized_name)
  where coalesce(ac.identity_count, 0) <> 1
),
ranked as (
  select
    c.*,
    row_number() over (
      partition by c.normalized_name
      order by c.priority, c.display_name
    ) as rn
  from candidate c
  where c.normalized_name <> ''
)
select gen_random_uuid() as player_id, normalized_name, display_name
from ranked
where rn = 1;

insert into public.players(id, display_name)
