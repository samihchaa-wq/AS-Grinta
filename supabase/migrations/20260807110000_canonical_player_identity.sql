create table public.historical_match_players (
  match_id uuid not null references public.historical_match_scores(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete restrict,
  source_name text not null,
  is_present boolean not null default false,
  is_starter boolean not null default false,
  is_bench boolean not null default false,
  is_motm boolean not null default false,
  goals integer not null default 0 check (goals >= 0),
  is_goalkeeper boolean,
  x_pct numeric,
  y_pct numeric,
  position_code text,
  position_label text,
  created_at timestamptz not null default now(),
  primary key (match_id, player_id)
);

comment on table public.historical_match_players is
