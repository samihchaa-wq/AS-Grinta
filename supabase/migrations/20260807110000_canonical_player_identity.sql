with field_row as (
  select
    h.match_id,
    btrim(e ->> 'name') as source_name,
    private.normalize_player_name(e ->> 'name') as normalized_name,
    true as is_present,
    true as is_starter,
    false as is_bench,
    false as is_motm,
    0::integer as goals,
    (e ->> 'is_gk')::boolean as is_goalkeeper,
    (e ->> 'x_pct')::numeric as x_pct,
    (e ->> 'y_pct')::numeric as y_pct,
    e ->> 'position_code' as position_code,
    e ->> 'position_label' as position_label
  from public.historical_match_details h
  cross join lateral jsonb_array_elements(coalesce(h.field_players, '[]'::jsonb)) e
  where btrim(coalesce(e ->> 'name', '')) <> ''
    and private.normalize_player_name(e ->> 'name')
      <> private.normalize_player_name('Poste laissé vide')
),
bench_row as (
  select
    h.match_id,
    btrim(n.player_name) as source_name,
    private.normalize_player_name(n.player_name) as normalized_name,
    true, false, true, false, 0::integer,
    null::boolean, null::numeric, null::numeric, null::text, null::text
  from public.historical_match_details h
  cross join lateral jsonb_array_elements_text(coalesce(h.bench_players, '[]'::jsonb)) n(player_name)
  where btrim(coalesce(n.player_name, '')) <> ''
),
present_row as (
  select
    h.match_id,
    btrim(n.player_name) as source_name,
    private.normalize_player_name(n.player_name) as normalized_name,
    true, false, false, false, 0::integer,
    null::boolean, null::numeric, null::numeric, null::text, null::text
  from public.historical_match_details h
  cross join lateral jsonb_array_elements_text(coalesce(h.present_names, '[]'::jsonb)) n(player_name)
  where btrim(coalesce(n.player_name, '')) <> ''
),
scorer_row as (
  select
    h.match_id,
    btrim(e ->> 'name') as source_name,
    private.normalize_player_name(e ->> 'name') as normalized_name,
    true, false, false, false,
    coalesce((e ->> 'goals')::integer, 0),
    null::boolean, null::numeric, null::numeric, null::text, null::text
  from public.historical_match_details h
  cross join lateral jsonb_array_elements(coalesce(h.scorers, '[]'::jsonb)) e
  where btrim(coalesce(e ->> 'name', '')) <> ''
),
motm_row as (
  select
    h.match_id,
    btrim(n.player_name) as source_name,
    private.normalize_player_name(n.player_name) as normalized_name,
    true, false, false, true, 0::integer,
    null::boolean, null::numeric, null::numeric, null::text, null::text
  from public.historical_match_details h
  cross join lateral jsonb_array_elements_text(coalesce(h.motm_names, '[]'::jsonb)) n(player_name)
  where btrim(coalesce(n.player_name, '')) <> ''
),
all_row as (
  select * from field_row
  union all select * from bench_row
  union all select * from present_row
  union all select * from scorer_row
  union all select * from motm_row
),
aggregated as (
  select
    r.match_id,
    r.normalized_name,
    min(r.source_name) as source_name,
    bool_or(r.is_present) as is_present,
    bool_or(r.is_starter) as is_starter,
    bool_or(r.is_bench) as is_bench,
    bool_or(r.is_motm) as is_motm,
    sum(r.goals)::integer as goals,
    bool_or(r.is_goalkeeper) filter (where r.is_goalkeeper is not null) as is_goalkeeper,
    max(r.x_pct) as x_pct,
    max(r.y_pct) as y_pct,
    max(r.position_code) as position_code,
    max(r.position_label) as position_label
  from all_row r
  where r.normalized_name <> private.normalize_player_name('Poste laissé vide')
  group by r.match_id, r.normalized_name
)
insert into public.historical_match_players(
  match_id, player_id, source_name, is_present, is_starter, is_bench,
  is_motm, goals, is_goalkeeper, x_pct, y_pct, position_code, position_label
)
select
  a.match_id,
  m.player_id,
  a.source_name,
  a.is_present,
  a.is_starter,
  a.is_bench,
  a.is_motm,
  a.goals,
  a.is_goalkeeper,
  a.x_pct,
  a.y_pct,
  a.position_code,
  a.position_label
from aggregated a
join _archive_player_map m using (normalized_name)
on conflict (match_id, player_id) do update
set
  is_present = excluded.is_present or historical_match_players.is_present,
  is_starter = excluded.is_starter or historical_match_players.is_starter,
  is_bench = excluded.is_bench or historical_match_players.is_bench,
  is_motm = excluded.is_motm or historical_match_players.is_motm,
  goals = greatest(excluded.goals, historical_match_players.goals),
  is_goalkeeper = coalesce(excluded.is_goalkeeper, historical_match_players.is_goalkeeper),
  x_pct = coalesce(excluded.x_pct, historical_match_players.x_pct),
  y_pct = coalesce(excluded.y_pct, historical_match_players.y_pct),
  position_code = coalesce(excluded.position_code, historical_match_players.position_code),
  position_label = coalesce(excluded.position_label, historical_match_players.position_label);

-- Helpers privés pour garantir une identité aux nouvelles lignes sans réintroduire
-- de fusion automatique par nom lors de la création d'un joueur moderne.
create or replace function private.create_player_identity(p_display_name text)
returns uuid
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_player_id uuid;
  v_display_name text := nullif(btrim(p_display_name), '');
begin
  if v_display_name is null then
    raise exception 'Player display name is required' using errcode = '22023';
  end if;

  insert into public.players(display_name)
  values (v_display_name)
  returning id into v_player_id;

  insert into public.player_aliases(player_id, alias)
  values (v_player_id, v_display_name)
  on conflict do nothing;

  return v_player_id;
end;
$function$;

revoke all on function private.create_player_identity(text) from public, anon, authenticated;

create or replace function private.ensure_profile_player_identity()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
begin
  if coalesce(new.email, '') = 'historique@as-grinta.invalid' then
    return new;
  end if;

  if new.player_id is null then
    new.player_id := private.create_player_identity(
      coalesce(
        nullif(btrim(concat_ws(' ', new.first_name, nullif(new.last_name, ''))), ''),
        nullif(btrim(new.username), ''),
        'Joueur'
      )
    );
  end if;

  return new;
end;
$function$;

create or replace function private.ensure_season_player_identity()
returns trigger
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_profile_player_id uuid;
begin
  if new.player_id is not null then
    return new;
  end if;

  if new.profile_id is not null then
    select p.player_id into v_profile_player_id
    from public.profiles p
