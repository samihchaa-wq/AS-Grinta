-- Résolution directe des libellés d'archives. Le mapping temporaire mémorise
-- le choix prudent effectué ci-dessus, y compris lorsqu'un nom était ambigu.
create temporary table _archive_player_map on commit drop as
with archive_names as (
  select distinct
    private.normalize_player_name(n.player_name) as normalized_name,
    btrim(n.player_name) as display_name
  from public.historical_match_details h
  cross join lateral (
    select e ->> 'name' as player_name
    from jsonb_array_elements(coalesce(h.field_players, '[]'::jsonb)) e
    union all
    select jsonb_array_elements_text(coalesce(h.bench_players, '[]'::jsonb))
    union all
    select jsonb_array_elements_text(coalesce(h.present_names, '[]'::jsonb))
    union all
    select e ->> 'name'
    from jsonb_array_elements(coalesce(h.scorers, '[]'::jsonb)) e
    union all
    select jsonb_array_elements_text(coalesce(h.motm_names, '[]'::jsonb))
  ) n
  where btrim(coalesce(n.player_name, '')) <> ''
    and private.normalize_player_name(n.player_name)
      <> private.normalize_player_name('Poste laissé vide')
),
unique_alias as (
  select
    private.normalize_player_name(a.alias) as normalized_name,
    min(a.player_id::text)::uuid as player_id
  from public.player_aliases a
  group by private.normalize_player_name(a.alias)
  having count(distinct a.player_id) = 1
)
select
  an.normalized_name,
  an.display_name,
  coalesce(seed.player_id, ua.player_id) as player_id
from archive_names an
left join _canonical_player_seed seed using (normalized_name)
left join unique_alias ua using (normalized_name);

do $assertions$
begin
  if exists (
    select 1
    from public.profiles p
    where coalesce(p.email, '') <> 'historique@as-grinta.invalid'
      and p.player_id is null
  ) then
    raise exception 'Canonical identity backfill failed for profiles';
  end if;

  if exists (select 1 from public.season_players where player_id is null) then
    raise exception 'Canonical identity backfill failed for season_players';
  end if;

  if exists (select 1 from public.guest_players where player_id is null) then
    raise exception 'Canonical identity backfill failed for guest_players';
  end if;

  if exists (
    select 1 from public.historical_player_statistics where player_id is null
  ) then
    raise exception 'Canonical identity backfill failed for historical statistics';
  end if;

  if exists (select 1 from _archive_player_map where player_id is null) then
    raise exception 'Canonical identity backfill failed for archived match names';
  end if;

  if exists (
    select 1
    from public.season_players sp
    join public.profiles p on p.id = sp.profile_id
    where p.player_id is not null
      and sp.player_id is distinct from p.player_id
  ) then
    raise exception 'Season/profile canonical identities disagree';
  end if;

  if exists (
    select 1
    from public.historical_player_statistics h
    join public.profiles p on p.id = h.profile_id
    where p.player_id is not null
      and h.player_id is distinct from p.player_id
  ) then
    raise exception 'Historical/profile canonical identities disagree';
  end if;
end
$assertions$;

