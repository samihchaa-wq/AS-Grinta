-- Une personne réelle = une identité canonique durable.
-- Les comptes, effectifs, invités, statistiques et archives deviennent des
-- contextes qui pointent vers public.players au lieu d'être des identités.

create or replace function private.normalize_player_name(p_name text)
returns text
language sql
immutable
strict
set search_path to ''
as $function$
  select lower(regexp_replace(btrim(p_name), '\s+', ' ', 'g'));
$function$;

revoke all on function private.normalize_player_name(text) from public, anon, authenticated;

