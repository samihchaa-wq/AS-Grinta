begin;

-- Savoir si une notification a vraiment été vue.
--
-- Le 14 octobre 2026, l'ouverture des disponibilités de 12 h est partie vers
-- les 20 joueurs ; Apple et Google ont accepté les 26 envois. Plusieurs
-- joueurs ont pourtant dit ne rien avoir reçu, et rien côté serveur ne
-- permettait de le vérifier : « accepté » veut seulement dire qu'Apple ou
-- Google s'en charge, pas que le téléphone l'a affiché.
--
-- Deux causes restaient invisibles :
--
-- 1. Notifications coupées dans les réglages du téléphone. L'abonnement
--    reste valide, les envois sont acceptés, rien ne s'affiche, et la cloche
--    de l'application restait verte.
-- 2. Notification reçue mais jamais affichée par le téléphone.
--
-- L'application transmet désormais, à chaque ouverture :
--
-- - l'autorisation d'affichage du téléphone, rangée sur son abonnement
--   (notification_permission, device_reported_at) ;
-- - les accusés d'affichage notés par le service worker depuis la dernière
--   ouverture (private.push_display_receipts : quelle notification, quand).
--
-- Un envoi accepté sans accusé, sur un téléphone revenu depuis dans
-- l'application, n'a pas été affiché.

alter table public.push_subscriptions
  add column if not exists notification_permission text,
  add column if not exists device_reported_at timestamptz;

alter table public.push_subscriptions
  drop constraint if exists push_subscriptions_notification_permission_check;

alter table public.push_subscriptions
  add constraint push_subscriptions_notification_permission_check
  check (
    notification_permission is null
    or notification_permission in ('granted', 'denied', 'default')
  );

comment on column public.push_subscriptions.notification_permission is
  'Autorisation d affichage déclarée par le téléphone à sa dernière ouverture de l application (granted, denied, default). NULL : jamais déclarée.';

comment on column public.push_subscriptions.device_reported_at is
  'Dernière fois que le téléphone a déclaré son autorisation d affichage.';

create table if not exists private.push_display_receipts (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  endpoint_host text,
  tag text not null,
  displayed_at timestamptz not null,
  reported_at timestamptz not null default now()
);

comment on table private.push_display_receipts is
  'Notifications réellement affichées par un téléphone (étiquette et heure), transmises par l application à sa réouverture. Conservées 90 jours.';

create unique index if not exists push_display_receipts_unique_idx
  on private.push_display_receipts (profile_id, tag, displayed_at);

create index if not exists push_display_receipts_reported_at_idx
  on private.push_display_receipts (reported_at);

-- Lecture et écriture réservées aux fonctions ci-dessous et au service
-- interne : refus par défaut.
alter table private.push_display_receipts enable row level security;
revoke all on table private.push_display_receipts from public, anon, authenticated;

create or replace function public.report_my_push_device(
  p_endpoint text,
  p_permission text,
  p_receipts jsonb default '[]'::jsonb
)
returns void
language plpgsql
security definer
set search_path to ''
as $function$
declare
  v_actor uuid := (select auth.uid());
  v_permission text := case
    when p_permission in ('granted', 'denied', 'default') then p_permission
    else null
  end;
  v_endpoint text := nullif(btrim(coalesce(p_endpoint, '')), '');
  v_host text;
begin
  if v_actor is null then
    raise exception 'Authentication required' using errcode = '42501';
  end if;

  if not exists (
    select 1
    from public.profiles profile
    where profile.id = v_actor
      and profile.status = 'active'
  ) then
    raise exception 'Active profile not found' using errcode = '42501';
  end if;

  if v_endpoint is not null and length(v_endpoint) <= 2048 then
    v_host := substring(v_endpoint from '^https://([^/]+)/');

    -- Seul l'abonnement du demandeur est mis à jour.
    update public.push_subscriptions subscription
    set notification_permission = v_permission,
        device_reported_at = now()
    where subscription.endpoint = v_endpoint
      and subscription.profile_id = v_actor;
  end if;

  if jsonb_typeof(p_receipts) = 'array' then
    insert into private.push_display_receipts (
      profile_id, endpoint_host, tag, displayed_at
    )
    -- Le CASE garantit qu'aucune date mal formée n'est convertie : une
    -- conversion ratée annulerait tout l'appel.
    select distinct on (parsed.tag, parsed.displayed_at)
      v_actor,
      left(v_host, 255),
      parsed.tag,
      parsed.displayed_at
    from (
      select
        left(btrim(receipt.value ->> 'tag'), 200) as tag,
        case
          when coalesce(receipt.value ->> 'at', '')
            ~ '^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])T([01]\d|2[0-3]):[0-5]\d:[0-5]\d(\.\d{1,6})?Z$'
          then (receipt.value ->> 'at')::timestamptz
        end as displayed_at
      from jsonb_array_elements(p_receipts) with ordinality as receipt(value, position)
      where receipt.position <= 50
        and jsonb_typeof(receipt.value) = 'object'
        and nullif(btrim(coalesce(receipt.value ->> 'tag', '')), '') is not null
    ) parsed
    where parsed.displayed_at
      between now() - interval '30 days' and now() + interval '5 minutes'
    on conflict (profile_id, tag, displayed_at) do nothing;
  end if;

  delete from private.push_display_receipts receipt
  where receipt.reported_at < now() - interval '90 days';
end;
$function$;

comment on function public.report_my_push_device(text, text, jsonb) is
  'Déclare l autorisation d affichage du téléphone du demandeur et les notifications qu il a réellement affichées. N écrit que pour le compte connecté, profil actif exigé, 50 accusés au plus par appel.';

revoke all on function public.report_my_push_device(text, text, jsonb)
  from public, anon;
grant execute on function public.report_my_push_device(text, text, jsonb)
  to authenticated, service_role;

commit;
